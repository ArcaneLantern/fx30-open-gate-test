"""Write expected_cardspeed_fx30_v1.h for helper_fx30/fx30cardspeed.c from modding/designs/cardspeed_off_fx30_v1.json (session MR1, 2026-11-27).

  C:\\Python313\\python.exe -B gen_fx30_cardspeed.py        (or work\\venv\\Scripts\\python.exe -I -B ...)

The design comes from build/media_rate_check.py (the card-speed check of movie recording, libmpr.so RateCheck::GetMediaTransferRateInh).
Every byte is checked once more against libmpr.so 6.01 here (work/extracted/fx30_601) before it is written: the file's SHA-256, the ELF
header, the guard range (the compare helper and the whole check) and both sites' stock bytes.
"""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
LIBMPR = ROOT / "work/extracted/fx30_601/0700_part_image/dev/nflasha15/lib/libmpr.so"
DESIGN = ROOT / "modding/designs/cardspeed_off_fx30_v1.json"
OUT = HERE / "expected_cardspeed_fx30_v1.h"


def c_rows(b, indent="    "):
    return [indent + ", ".join("0x%02x" % x for x in b[k:k + 16]) + "," for k in range(0, len(b), 16)]


def main():
    d = json.loads(DESIGN.read_text(encoding="utf8"))
    data = LIBMPR.read_bytes()
    assert d["build"] == "fx30_601" and d["artifact_sha256"]["libmpr.so"] == hashlib.sha256(data).hexdigest()
    assert d["verify"]["ok"], "the design's emulation check did not pass"
    g_va, g_len = int(d["guard"]["va"], 16), d["guard"]["len"]
    guard = bytes.fromhex(d["guard"]["stock"])
    assert int(d["guard"]["file_off"], 16) == g_va and data[g_va:g_va + g_len] == guard and len(guard) == g_len  # code segment: file offset = VA
    elf = bytes.fromhex(d["elf_header"]["stock"])
    assert data[:64] == elf and len(elf) == 64
    rows = []
    for s in d["sites"]:
        va, stock, new = int(s["va"], 16), bytes.fromhex(s["stock"]), bytes.fromhex(s["new"])
        assert int(s["file_off"], 16) == va and len(stock) == len(new) == 4 and data[va:va + 4] == stock and stock != new
        assert g_va <= va and va + 4 <= g_va + g_len and va % 4 == 0
        rows.append("    { 0x%xUL, { %s }, { %s } },   /* %s */" % (va, ", ".join("0x%02x" % x for x in stock), ", ".join("0x%02x" % x for x in new),
                                                                     s["label"].replace("*/", "")))
    fn = d["function"]
    text = "\n".join([
        "/* Generated by helper_fx30/gen_fx30_cardspeed.py from modding/designs/cardspeed_off_fx30_v1.json (FX30 6.01). Do not edit. */",
        "/* libmpr.so %s...: the ELF header, the guard range and both sites' stock bytes were compared with this file. */" % d["artifact_sha256"]["libmpr.so"][:16],
        '#define CS_DESIGN "%s"' % d["design"],
        "#define CS_FUNC 0x%sUL                     /* RateCheck::GetMediaTransferRateInh, %d bytes */" % (fn["va"][2:], fn["size"]),
        "#define CS_GUARD_VA 0x%xUL                 /* the compare helper (%s) and the whole check, as in the file */" % (g_va, d["compare_helper"]),
        "#define CS_GUARD_LEN %dU" % g_len,
        "struct cs_site { u64 va; u8 stock[4]; u8 changed[4]; };",
        "static const struct cs_site cs_sites[] = {    /* apply order; put back runs in reverse */",
        *rows, "};",
        "static const u8 cs_elf[64] = {",
        *c_rows(elf), "};",
        "static const u8 cs_guard[%d] = {" % g_len,
        *c_rows(guard), "};", ""])
    OUT.write_text(text, encoding="utf8", newline="\n")
    print("%s: %d sites, guard %d bytes at 0x%x" % (OUT.name, len(rows), g_len, g_va))


if __name__ == "__main__":
    main()
