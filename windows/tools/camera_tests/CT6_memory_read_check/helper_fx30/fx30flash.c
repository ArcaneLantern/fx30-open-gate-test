/*
 * fx30flash: the external-flash test step for the FX30 (ILME-FX30) firmware 6.01, design fx30flash_v2 (session HS1, 2026-11-27).
 *
 * NOT RUN ON A CAMERA. Loaded the way the other FX30 helpers are (fx30read.c, readcheck.c): the service file-write command writes
 * /tmp/jiritsu/libJit.so and loads it at once; loading runs the constructor below, once, inside the service process, which is the
 * camera's main application process (appFw.so and libObj.so are mapped in it).
 *
 * What it does, complete (modding/FX30_FLASH_ENABLE.md):
 *   level 18  READ-ONLY. For every entry of the design, what this process holds now: the appFw.so menu flags and rule slots (STOCK,
 *             TARGET or OTHER), their guards (SAME or DIFFERS), libObj.so's code guards, and the shoe table: libObj.so's InfraHotshoe
 *             instance (pointer at libObj + 0x2cde00, first word = load base + 0x251c38), its count (42) and its heap copy of the table at
 *             +0x60, compared word by word with the stock table, the three sites reported as STOCK/TARGET/OTHER. Also prints the instance's
 *             first 128 bytes and the 42 entries (shoe ID, key) for the report. Verdict READY, APPLIED or NOT READY.
 *   level 19  the same checks, then writes: the three shoe-table words, the twelve menu flags, the two rule slots, each read back.
 *   level 20  the same with the two byte sets exchanged and the order reversed: puts everything back.
 * Every read of this process's memory other than its own buffers goes through pread64 on /proc/self/mem, and every write through pwrite64
 * on it: an address that is not mapped gives an error, never a fault. Before anything is written every guard must be as in the 6.01 files
 * (pointers as the loader relocated them: load base + addend), every site must hold the stock or the design's bytes, and the whole heap
 * table must be the stock table apart from the three sites. On any failure everything this run wrote is put back.
 * Nothing else is written: no file but the result, no coprocessor transfer, no library call (it has no imports), no mapping.
 * A cold boot (battery out) undoes it: appFw.so and libObj.so are loaded again and the table is built again from the stored setting.
 * If the result file already exists it does nothing at all.
 *
 * Build: build_fx30_flash.sh (AArch64, freestanding, no libc). -DLEVEL=18|19|20.
 */
typedef unsigned char u8;
typedef unsigned int u32;
typedef unsigned long u64;
typedef long i64;
#include "expected_flash_fx30_v2.h"        /* generated by gen_fx30_flash.py */

