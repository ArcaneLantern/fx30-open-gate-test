#define TOTAL_CAP (256 * 1024)
#define MAPS_CAP (384 * 1024)
#define N_APP (sizeof fl_app / sizeof fl_app[0])
#define N_OBJ (sizeof fl_obj / sizeof fl_obj[0])
#define N_SHOE (sizeof fl_shoe / sizeof fl_shoe[0])
