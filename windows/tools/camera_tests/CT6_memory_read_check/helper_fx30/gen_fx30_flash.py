"""Write expected_flash_fx30_v2.h for helper_fx30/fx30flash.c from modding/designs/fx30flash_v2.json (session HS1, 2026-11-27).

  C:\\Python313\\python.exe -B gen_fx30_flash.py        (or work\\venv\\Scripts\\python.exe -I -B ...)

Every entry is checked once more against the 6.01 files here (appFw.so and libObj.so from work/extracted/fx30_601) before it is written:
literal bytes as in the file, pointers as their relocation gives them (load base + addend) or null with no relocation.
"""
import hashlib
import io
import json
import struct
from pathlib import Path

from elftools.elf.elffile import ELFFile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
LIB = ROOT / "work/extracted/fx30_601/0700_part_image/dev/nflasha15/lib"
DESIGN = ROOT / "modding/designs/fx30flash_v2.json"
OUT = HERE / "expected_flash_fx30_v2.h"
DATA_DELTA = 0x10000                                    # appFw.so and libObj.so: data segment file offset = virtual address - 0x10000


def relocs(d):
    out = {}
    for sec in ELFFile(io.BytesIO(d)).iter_sections():
        if sec.header.sh_type == "SHT_RELA":
            for r in sec.iter_relocations():
                out[r["r_offset"]] = (r["r_info_type"], r["r_addend"])
    return out


def c_bytes(b):
    b = bytes(b) + bytes(16 - len(b))
    return "{ " + ", ".join("0x%02x" % x for x in b) + " }"


def row(e, data, rel, seg0_end):
    va, n = int(e["va"], 16), e["len"]
    fo = va if va < seg0_end else va - DATA_DELTA
    assert int(e["file_off"], 16) == fo and e["seg"] == (0 if va < seg0_end else 1)
    if e["pointer"]:
        def enc(p):
            kind, v = p
            assert kind in ("rel", "null")
            return (1 if kind == "rel" else 0), struct.pack("<Q", v)
        sr, sb = enc(e["stock"])
        if sr:
            assert rel.get(va) == (1027, struct.unpack("<Q", sb)[0]), e
        else:
            assert va not in rel and data[fo:fo + 8] == bytes(8), e
        nr, nb = enc(e["new"]) if e["kind"] else (0, bytes(8))
        return "    { 0x%xUL, 8, %d, 1, %d, %d, %d, %s, %s },   /* %s */" % (va, e["kind"], e["seg"], sr, nr, c_bytes(sb), c_bytes(nb), e["label"])
    stock = bytes.fromhex(e["stock"])
    assert data[fo:fo + n] == stock, e
    new = bytes.fromhex(e["new"]) if e["kind"] else bytes(n)
    return "    { 0x%xUL, %d, %d, 0, %d, 0, 0, %s, %s },   /* %s */" % (va, n, e["kind"], e["seg"], c_bytes(stock), c_bytes(new), e["label"].replace("*/", ""))


def main():
    d = json.loads(DESIGN.read_text(encoding="utf8"))
    app, obj = (LIB / "appFw.so").read_bytes(), (LIB / "libObj.so").read_bytes()
    assert d["artifact_sha256"] == {"appFw.so": hashlib.sha256(app).hexdigest(), "libObj.so": hashlib.sha256(obj).hexdigest()}
    seg0 = lambda b: next(s for s in ELFFile(io.BytesIO(b)).iter_segments() if s["p_type"] == "PT_LOAD")["p_filesz"]
    ra, ro = relocs(app), relocs(obj)
    app_rows = [row(e, app, ra, seg0(app)) for e in d["menu_flags"] + d["rule_slots"]]      # apply order: menus, then the rule slots
    obj_rows = [row(e, obj, ro, seg0(obj)) for e in d["libobj_guards"]]
    ch = d["libobj_chain"]
    iv = lambda v: int(v, 0) if isinstance(v, str) else int(v)
    table = bytes.fromhex(d["shoe_table_heap_stock"])
    assert len(table) == iv(ch["entries"]) * iv(ch["entry"])
    shoe = []
    for s in d["shoe_sites"]:
        i, off = s["entry"], int(s["heap_off"], 16)
        assert off == 32 * i + 4 and table[off:off + 4].hex() == s["stock"]
        shoe.append("    { %d, 0x%08xU, 0x%08xU },   /* entry %d: shoe ID %s, %s */" % (i, struct.unpack("<I", bytes.fromhex(s["stock"]))[0],
                                                                                    struct.unpack("<I", bytes.fromhex(s["new"]))[0], i, s["shoe_id"], s["input"]))
    tab_rows = ["    " + ", ".join("0x%02x" % x for x in table[k:k + 16]) + "," for k in range(0, len(table), 16)]
    text = "\n".join([
        "/* Generated by helper_fx30/gen_fx30_flash.py from modding/designs/fx30flash_v2.json (FX30 6.01). Do not edit. */",
        "/* appFw.so %s..., libObj.so %s... Stock bytes and relocations were compared with these files. */" % (d["artifact_sha256"]["appFw.so"][:16], d["artifact_sha256"]["libObj.so"][:16]),
        '#define FL_DESIGN "%s"' % d["design"],
        "#define FL_DATA_DELTA 0x%xUL                 /* data segment: file offset = virtual address - this */" % DATA_DELTA,
        "#define FL_OBJ_INST_PTR %sUL             /* libObj.so .bss: the InfraHotshoe instance (infra_hotshoe_init keeps it) */" % ch["inst_ptr"],
        "#define FL_OBJ_REFCOUNT %sUL             /* its reference count */" % ch["refcount"],
        "#define FL_OBJ_VTABLE %sUL               /* the instance's first word: load base + this (vtable 0x251c28 + 16) */" % ch["vtable_point"],
        "#define FL_OBJ_COUNT_OFF 0x%xU                   /* instance + this: number of entries */" % iv(ch["count_off"]),
        "#define FL_OBJ_ARRAY_OFF 0x%xU                   /* instance + this: the heap copy of the table */" % iv(ch["array_off"]),
        "#define FL_ENTRIES %dU" % iv(ch["entries"]),
        "#define FL_ENTRY %dU" % iv(ch["entry"]),
        "/* kind 1: a site, 0: a guard. ptr 1: an 8-byte pointer whose bytes are an addend; *_rel 1: the load base is added to it, 0: it is null. */",
        "struct fl_e { u64 va; u8 len; u8 kind; u8 ptr; u8 seg; u8 stock_rel; u8 new_rel; u8 stock[16]; u8 changed[16]; };",
        "static const struct fl_e fl_app[] = {         /* appFw.so: the menu flags, then the rule slots (apply order) */",
        *app_rows, "};",
        "static const struct fl_e fl_obj[] = {         /* libObj.so: code that builds and reads the table (guards only) */",
        *obj_rows, "};",
        "struct fl_s { u32 entry; u32 stock; u32 changed; };",
        "static const struct fl_s fl_shoe[] = {        /* word 1 (the key code) of three entries of the heap table */",
        *shoe, "};",
        "static const u8 fl_table[%d] = {               /* the heap table as KeyConfigAlloc makes it from the stock setting: {shoe ID, key, ...} */" % len(table),
        *tab_rows, "};", ""])
    OUT.write_text(text, encoding="utf8", newline="\n")
    print("%s: %d appFw.so entries (%d sites), %d libObj.so guards, %d shoe sites, table %d bytes" % (
        OUT.name, len(app_rows), sum(e["kind"] for e in d["menu_flags"] + d["rule_slots"]), len(obj_rows), len(shoe), len(table)))


if __name__ == "__main__":
    main()
